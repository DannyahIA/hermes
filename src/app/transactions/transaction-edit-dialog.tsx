'use client';

import { useState, useTransition } from 'react';
import { useFormStatus } from 'react-dom';

import { fileUnderNewCategoryAction } from '@/app/dashboard/actions';
import { NEW_CATEGORY_OPTION } from '@/app/dashboard/category-picker';
import {
  type ActionResult,
  updateInstallmentAction,
  updateTransactionAction,
} from '@/app/transactions/actions';
import { Alert, AlertDescription } from '@/components/ui/alert';
import { Button } from '@/components/ui/button';
import {
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog';
import { DialogForm } from '@/components/ui/dialog-form';
import { Input } from '@/components/ui/input';
import { FIELD_BASE_CLASSES } from '@/shared/constants/field-styles';

const INITIAL_STATE: ActionResult = { success: false };

export interface EditableTransaction {
  id: string;
  description: string;
  amount: number;
  /** The calendar day it happened: "2026-10-13". */
  day: string;
  categoryId: string | null;
  /** Generated by an installment plan: enables "apply to the next ones". */
  isInstallment: boolean;
  /** False for a card bill payment, which never takes a category. */
  takesCategory: boolean;
}

interface TransactionEditDialogProps {
  /** The transaction being edited; null keeps the dialog closed. */
  transaction: EditableTransaction | null;
  /** Every category, archived ones too: the current one must stay listed. */
  categories: Array<{ id: string; name: string; archived?: boolean }>;
  onClose: () => void;
}

/**
 * The one editing surface for both a plain transaction and an installment
 * (see ui-ux.md: "Um modal deve abrir sempre da mesma forma") — the only
 * difference is which server action it posts to and whether the
 * "apply to future installments" checkbox is shown. A list mounts one and
 * opens it for whichever row asked.
 */
export function TransactionEditDialog({
  transaction,
  categories,
  onClose,
}: TransactionEditDialogProps) {
  return (
    <DialogForm
      open={transaction !== null}
      onOpenChange={(open) => {
        if (!open) onClose();
      }}
      action={
        transaction?.isInstallment
          ? updateInstallmentAction
          : updateTransactionAction
      }
      initialState={INITIAL_STATE}
    >
      {({ state, formAction }) =>
        transaction && (
          <EditForm
            transaction={transaction}
            categories={categories}
            state={state}
            formAction={formAction}
            onCancel={onClose}
          />
        )
      }
    </DialogForm>
  );
}

function EditForm({
  transaction,
  categories,
  state,
  formAction,
  onCancel,
}: {
  transaction: EditableTransaction;
  categories: TransactionEditDialogProps['categories'];
  state: ActionResult;
  formAction: (formData: FormData) => void;
  onCancel: () => void;
}) {
  const [day, setDay] = useState(transaction.day);
  const [categoryId, setCategoryId] = useState(transaction.categoryId ?? '');
  const [naming, setNaming] = useState(false);
  const [newName, setNewName] = useState('');
  const [newError, setNewError] = useState<string | null>(null);
  const [made, setMade] = useState<Array<{ id: string; name: string }>>([]);
  const [creating, startTransition] = useTransition();
  const trimmedName = newName.trim();
  // An archived category takes no new transactions, but the one this
  // transaction already has must stay selected.
  const options = [
    ...categories.filter(
      (category) =>
        !category.archived || category.id === transaction.categoryId,
    ),
    ...made.filter(
      (category) => !categories.some((known) => known.id === category.id),
    ),
  ];

  function backToSelect() {
    setNaming(false);
    setNewName('');
    setNewError(null);
  }

  function createCategory() {
    if (!trimmedName || creating) return;
    startTransition(async () => {
      const result = await fileUnderNewCategoryAction({
        transactionIds: [transaction.id],
        name: trimmedName,
      });
      if (!result.success) {
        setNewError(result.error);
        return;
      }
      setMade((current) => [
        ...current,
        { id: result.category.id, name: result.category.name },
      ]);
      setCategoryId(result.category.id);
      backToSelect();
    });
  }

  return (
    <>
      <DialogHeader>
        <DialogTitle>Editar transação</DialogTitle>
        <DialogDescription>
          {transaction.takesCategory
            ? 'Altere o valor, a data, a descrição ou a categoria.'
            : 'Altere o valor, a data ou a descrição.'}
        </DialogDescription>
      </DialogHeader>

      <form action={formAction} className="space-y-4">
        <input type="hidden" name="id" value={transaction.id} />

        {state.error && (
          <Alert variant="error">
            <AlertDescription>{state.error}</AlertDescription>
          </Alert>
        )}

        <div className="space-y-2">
          <label className="text-sm font-medium" htmlFor="edit-description">
            Descrição
          </label>
          <Input
            id="edit-description"
            name="description"
            defaultValue={transaction.description}
            required
          />
        </div>

        <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
          <div className="space-y-2">
            <label className="text-sm font-medium" htmlFor="edit-amount">
              Valor
            </label>
            <Input
              id="edit-amount"
              name="amount"
              type="number"
              step="0.01"
              min="0.01"
              defaultValue={transaction.amount}
              required
            />
          </div>
          <div className="space-y-2">
            <label className="text-sm font-medium" htmlFor="edit-occurredAt">
              Data
            </label>
            {/* Sent only when the day changes, so the time it happened at
                survives an edit to anything else. */}
            <Input
              id="edit-occurredAt"
              name={day === transaction.day ? undefined : 'occurredAt'}
              type="date"
              value={day}
              onChange={(event) => setDay(event.target.value)}
              required
            />
          </div>
        </div>

        {transaction.takesCategory && (
          <div className="space-y-2">
            <label className="text-sm font-medium" htmlFor="edit-categoryId">
              Categoria
            </label>
            {naming ? (
              <>
                {/* The form still sends the category it had. */}
                <input type="hidden" name="categoryId" value={categoryId} />
                <div className="flex items-center gap-2">
                  <Input
                    aria-label="Nome da categoria"
                    autoFocus
                    maxLength={60}
                    value={newName}
                    onChange={(event) => setNewName(event.target.value)}
                    onKeyDown={(event) => {
                      if (event.key === 'Enter') {
                        // Creates the category; the edit form must not submit.
                        event.preventDefault();
                        createCategory();
                      } else if (event.key === 'Escape') {
                        // Back to the select, and not out of the dialog.
                        event.preventDefault();
                        event.stopPropagation();
                        backToSelect();
                      }
                    }}
                  />
                  <Button
                    type="button"
                    disabled={!trimmedName || creating}
                    onClick={createCategory}
                  >
                    Criar
                  </Button>
                </div>
                {newError && (
                  <Alert variant="error">
                    <AlertDescription>{newError}</AlertDescription>
                  </Alert>
                )}
              </>
            ) : (
              <select
                id="edit-categoryId"
                name="categoryId"
                value={categoryId}
                onChange={(event) => {
                  if (event.target.value === NEW_CATEGORY_OPTION) {
                    setNaming(true);
                  } else {
                    setCategoryId(event.target.value);
                  }
                }}
                className={FIELD_BASE_CLASSES}
              >
                {/* Saving can't take a category away, so only an
                  uncategorized transaction offers "none". */}
                {!transaction.categoryId && (
                  <option value="">Sem categoria</option>
                )}
                {options.map((category) => (
                  <option key={category.id} value={category.id}>
                    {category.name}
                  </option>
                ))}
                <option value={NEW_CATEGORY_OPTION}>＋ Nova categoria…</option>
              </select>
            )}
          </div>
        )}

        {transaction.isInstallment && (
          <label className="flex items-center gap-2 text-sm">
            <input
              type="checkbox"
              name="propagateToFuture"
              className="border-input h-4 w-4 rounded"
            />
            Aplicar o novo valor às próximas parcelas
          </label>
        )}

        <DialogFooter>
          <Button type="button" variant="outline" onClick={onCancel}>
            Cancelar
          </Button>
          <SubmitButton />
        </DialogFooter>
      </form>
    </>
  );
}

function SubmitButton() {
  const { pending } = useFormStatus();
  return (
    <Button type="submit" disabled={pending}>
      {pending ? 'Salvando…' : 'Salvar alterações'}
    </Button>
  );
}
